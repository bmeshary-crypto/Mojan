/// محتوى بودكاست موجان: مواضيع يومية (رأي ورأي آخر) وحلقات جاهزة تُعرض عند تعذر توليد حلقة جديدة.
library;

class PodLine {
  const PodLine(this.who, this.text);

  /// 0 = المذيع الأول (المضيف)، 1 = المذيعة الثانية.
  final int who;
  final String text;

  Map<String, dynamic> toJson() => {'who': who, 'text': text};
}

class PodEpisode {
  const PodEpisode(this.topic, this.lines);
  final String topic;
  final List<PodLine> lines;

  Map<String, dynamic> toJson() => {'topic': topic, 'lines': [for (final l in lines) l.toJson()]};

  static PodEpisode? fromJson(Object? j) {
    if (j is! Map) return null;
    final topic = j['topic'];
    final raw = j['lines'];
    if (topic is! String || raw is! List) return null;
    final lines = <PodLine>[
      for (final l in raw)
        if (l is Map && l['text'] is String && (l['text'] as String).trim().isNotEmpty)
          PodLine((l['who'] as num?)?.toInt() == 1 ? 1 : 0, (l['text'] as String).trim()),
    ];
    if (lines.length < 4) return null;
    return PodEpisode(topic, lines);
  }
}

